const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const os = require("node:os");
const crypto = require("node:crypto");
const { exportData, restoreData, relocate } = require("../scripts/cloud-data");

test("encrypted migration preserves files, rebases paths, excludes secrets and disables imported automation", async (t) => {
  const base = await fs.mkdtemp(path.join(os.tmpdir(), "autosocial-migration-"));
  t.after(() => fs.rm(base, { recursive: true, force: true }));
  const source = path.join(base, "source"), target = path.join(base, "restored"), keyFile = path.join(base, "key");
  await fs.mkdir(path.join(source, "queue", "default", "calendar", "videos"), { recursive: true });
  await fs.mkdir(path.join(source, ".scheduler-state", "default"), { recursive: true });
  await fs.mkdir(path.join(source, ".profiles", "default", "instagram"), { recursive: true });
  const video = path.join(source, "queue", "default", "calendar", "videos", "photo.jpg");
  await fs.writeFile(video, Buffer.from([1, 2, 3, 4]));
  const postsFile = path.join(source, "queue", "default", "calendar", "posts.json");
  await fs.writeFile(postsFile, JSON.stringify([{ id: "example", mediaPath: video, videoPath: video, status: "scheduled", caption: "example content" }]));
  await fs.writeFile(path.join(source, ".env"), "TELEGRAM_BOT_TOKEN=secret-not-in-data\nDASHBOARD_PASSWORD_HASH=secret-hash\nDEFAULT_CAPTION=example\nHEADLESS=false\n");
  await fs.writeFile(path.join(source, ".profiles", "default", "instagram", "Cookies"), "Windows encrypted profile");
  await fs.writeFile(path.join(source, ".profiles", "default", "instagram", ".instagram-session.json"), JSON.stringify({ cookies: [] }));
  await fs.writeFile(path.join(source, ".scheduler-state", "runtime.json"), JSON.stringify({ "default:youtube": true }));
  await fs.writeFile(path.join(source, ".scheduler-state", "default", "youtube-scheduler-state.json"), JSON.stringify({ instantPost: true }));
  await fs.writeFile(keyFile, crypto.randomBytes(32));
  const backup = await exportData({ source, outputDir: path.join(base, "exports"), keyFile });
  assert.equal(backup.encrypted, true);
  assert.equal((await fs.readFile(backup.snapshot)).includes(Buffer.from("example content")), false);
  const result = await restoreData({ snapshot: backup.snapshot, target, keyFile });
  assert.equal(result.checksumsVerified, true);
  const [post] = JSON.parse(await fs.readFile(path.join(target, "queue", "default", "calendar", "posts.json"), "utf8"));
  assert.equal(post.mediaPath, path.join(target, "queue", "default", "calendar", "videos", "photo.jpg"));
  assert.deepEqual(await fs.readFile(post.mediaPath), Buffer.from([1, 2, 3, 4]));
  const env = await fs.readFile(path.join(target, "settings.env"), "utf8");
  assert.doesNotMatch(env, /secret|HEADLESS/);
  assert.match(env, /AUTOSOCIAL_START_BACKGROUND=false/);
  assert.equal(JSON.parse(await fs.readFile(path.join(target, ".scheduler-state", "runtime.json"), "utf8"))["default:youtube"], false);
  assert.equal(JSON.parse(await fs.readFile(path.join(target, ".scheduler-state", "default", "youtube-scheduler-state.json"), "utf8")).instantPost, false);
  await assert.rejects(fs.stat(path.join(target, ".profiles", "default", "instagram", "Cookies")), /ENOENT/);
  await assert.rejects(restoreData({ snapshot: backup.snapshot, target, keyFile }), /already exists/);
  assert.equal(JSON.parse(await fs.readFile(postsFile, "utf8"))[0].mediaPath, video);
  assert.equal(relocate("E:\\AutoSocial\\queue\\default\\photo.jpg", "E:\\AutoSocial", "/data"), "/data/queue/default/photo.jpg");
  assert.equal(relocate({ caption: "E:\\AutoSocial\\literal-text" }, "E:\\AutoSocial", "/data").caption, "E:\\AutoSocial\\literal-text");
  const forCloud = path.join(base, "cloud-staging");
  await restoreData({ snapshot: backup.snapshot, target: forCloud, keyFile, pathRoot: "/data" });
  assert.equal(JSON.parse(await fs.readFile(path.join(forCloud, "queue", "default", "calendar", "posts.json"), "utf8"))[0].mediaPath, "/data/queue/default/calendar/videos/photo.jpg");
});

test("modified ciphertext fails authentication before any data is installed", async (t) => {
  const base = await fs.mkdtemp(path.join(os.tmpdir(), "autosocial-tamper-"));
  t.after(() => fs.rm(base, { recursive: true, force: true }));
  const source = path.join(base, "source"), keyFile = path.join(base, "key");
  await fs.mkdir(source); await fs.writeFile(path.join(source, "accounts-state.json"), "{}");
  await fs.writeFile(keyFile, crypto.randomBytes(32));
  const backup = await exportData({ source, outputDir: path.join(base, "exports"), keyFile });
  const bytes = await fs.readFile(backup.snapshot); bytes[50] ^= 1;
  await fs.writeFile(backup.snapshot, bytes);
  const target = path.join(base, "restored");
  await assert.rejects(restoreData({ snapshot: backup.snapshot, target, keyFile }), /authenticat|Unsupported state/);
  await assert.rejects(fs.stat(target), /ENOENT/);
});
